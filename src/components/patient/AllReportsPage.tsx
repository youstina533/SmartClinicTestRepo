import React, { useState, useEffect } from 'react';
import { useAuth } from '../../context/AuthContext';
import { HealthRiskReport, RiskLevel } from '../../types';
import { MlServiceApi } from '../../services/mockApi';
import {
  FileText,
  Calendar,
  Sparkles,
  ArrowRight,
  Droplet,
  Heart,
  AlertCircle,
  CheckCircle2,
  AlertTriangle,
} from 'lucide-react';

interface AllReportsPageProps {
  onNavigate: (tab: string, context?: any) => void;
}

export function getRiskColorClass(level: RiskLevel): {
  badge: string;
  bar: string;
  text: string;
  bg: string;
  border: string;
} {
  switch (level) {
    case 'High':
      return {
        badge: 'bg-red-50 text-red-700 border-red-200',
        bar: 'bg-red-500',
        text: 'text-red-700',
        bg: 'bg-red-50',
        border: 'border-red-200',
      };
    case 'Medium':
      return {
        badge: 'bg-orange-50 text-orange-700 border-orange-200',
        bar: 'bg-orange-500',
        text: 'text-orange-700',
        bg: 'bg-orange-50',
        border: 'border-orange-200',
      };
    case 'Low':
    default:
      return {
        badge: 'bg-green-50 text-green-700 border-green-200',
        bar: 'bg-green-500',
        text: 'text-green-700',
        bg: 'bg-green-50',
        border: 'border-green-200',
      };
  }
}

export const AllReportsPage: React.FC<AllReportsPageProps> = ({ onNavigate }) => {
  const { user } = useAuth();
  const [reports, setReports] = useState<HealthRiskReport[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    loadReports();
  }, [user]);

  const loadReports = async () => {
    if (!user) return;
    setLoading(true);
    try {
      const data = await MlServiceApi.getAllReports(user.id);
      setReports(data);
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="max-w-6xl mx-auto px-4 sm:px-6 lg:px-8 py-10 space-y-8">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-200 pb-5">
        <div>
          <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-teal-50 text-teal-700 text-xs font-semibold mb-2 border border-teal-200/60">
            <FileText className="w-3.5 h-3.5" />
            Medical History
          </div>
          <h1 className="text-3xl font-extrabold text-slate-900 tracking-tight">
            All Health Risk Reports
          </h1>
          <p className="text-sm text-slate-500 mt-1">
            Historical diagnostic records generated by the SmartClinic AI health risk simulation.
          </p>
        </div>

        <button
          onClick={() => onNavigate('enter-health-data')}
          className="px-5 py-3 rounded-2xl bg-teal-600 hover:bg-teal-700 text-white font-bold text-xs transition shadow-md shadow-teal-600/20 flex items-center justify-center gap-2 cursor-pointer"
        >
          <Sparkles className="w-4 h-4" />
          Enter New Health Data
        </button>
      </div>

      {/* Reports List - Horizontal cards per prompt specification */}
      {loading ? (
        <div className="py-20 text-center text-xs text-slate-400 flex items-center justify-center gap-2">
          <span className="w-5 h-5 border-2 border-teal-600 border-t-transparent rounded-full animate-spin"></span>
          Loading clinical reports...
        </div>
      ) : reports.length === 0 ? (
        <div className="bg-white rounded-3xl p-14 text-center border border-slate-200 space-y-4">
          <div className="w-14 h-14 rounded-2xl bg-teal-50 text-teal-600 flex items-center justify-center mx-auto">
            <FileText className="w-7 h-7" />
          </div>
          <h3 className="text-lg font-bold text-slate-900">No reports yet</h3>
          <p className="text-xs text-slate-400 max-w-sm mx-auto leading-relaxed">
            You haven't generated any health risk assessments yet. Enter your health metrics to calculate personalized Diabetes and Heart disease risk.
          </p>
          <button
            onClick={() => onNavigate('enter-health-data')}
            className="px-5 py-2.5 rounded-xl bg-teal-600 text-white font-semibold text-xs hover:bg-teal-700 inline-block"
          >
            Enter Health Data Now
          </button>
        </div>
      ) : (
        <div className="space-y-4">
          {reports.map((report) => {
            const colors = getRiskColorClass(report.overallRiskLevel);

            return (
              <div
                key={report.id}
                onClick={() => onNavigate('report-detail', { reportId: report.id })}
                className="bg-white rounded-3xl p-6 border border-slate-200/90 shadow-sm hover:shadow-md hover:border-teal-300 transition cursor-pointer flex flex-col md:flex-row md:items-center justify-between gap-6 group"
              >
                {/* Left: Date & Disease Tags */}
                <div className="flex items-start gap-4">
                  <div className="w-12 h-12 rounded-2xl bg-teal-50 text-teal-700 flex items-center justify-center font-bold text-sm shrink-0 group-hover:scale-105 transition">
                    <Calendar className="w-5 h-5" />
                  </div>

                  <div className="space-y-1.5">
                    <div className="flex items-center gap-2">
                      <span className="text-sm font-extrabold text-slate-900">
                        Assessment Date: {report.date}
                      </span>
                      <span className="text-slate-300">•</span>
                      <div className="flex items-center gap-1.5">
                        {report.hasDiabetes && (
                          <span className="px-2 py-0.5 rounded-full text-[10px] font-bold bg-teal-50 text-teal-700 border border-teal-200 flex items-center gap-1">
                            <Droplet className="w-3 h-3" />
                            Diabetes
                          </span>
                        )}
                        {report.hasHeart && (
                          <span className="px-2 py-0.5 rounded-full text-[10px] font-bold bg-rose-50 text-rose-700 border border-rose-200 flex items-center gap-1">
                            <Heart className="w-3 h-3" />
                            Heart Disease
                          </span>
                        )}
                      </div>
                    </div>

                    {/* Breakdown preview */}
                    <div className="flex flex-wrap items-center gap-4 text-xs text-slate-500">
                      {report.diabetesResult && (
                        <span>
                          Diabetes Risk:{' '}
                          <strong className="text-slate-800">
                            {report.diabetesResult.riskPercentage}% (
                            {report.diabetesResult.riskLevel})
                          </strong>
                        </span>
                      )}
                      {report.heartResult && (
                        <span>
                          Heart Risk:{' '}
                          <strong className="text-slate-800">
                            {report.heartResult.riskPercentage}% ({report.heartResult.riskLevel})
                          </strong>
                        </span>
                      )}
                    </div>
                  </div>
                </div>

                {/* Right: Risk Result Badge & Open Action */}
                <div className="flex items-center justify-between md:justify-end gap-6 pt-4 md:pt-0 border-t md:border-t-0 border-slate-100">
                  <div className="text-right">
                    <div className="text-[11px] text-slate-400 uppercase font-semibold">
                      Max Risk Score
                    </div>
                    <div className="flex items-center gap-2 mt-0.5">
                      <span className="text-2xl font-black text-slate-900">
                        {report.overallRiskPercentage}%
                      </span>
                      {/* Risk Band: Red / Orange / Green */}
                      <span
                        className={`px-3 py-1 rounded-full text-xs font-black uppercase tracking-wider border ${colors.badge}`}
                      >
                        {report.overallRiskLevel} Risk
                      </span>
                    </div>
                  </div>

                  <div className="w-10 h-10 rounded-full bg-slate-50 text-slate-400 group-hover:bg-teal-50 group-hover:text-teal-600 flex items-center justify-center transition shrink-0">
                    <ArrowRight className="w-5 h-5" />
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
